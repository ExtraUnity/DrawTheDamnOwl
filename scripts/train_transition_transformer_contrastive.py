def set_seed(seed: int) -> None:
    np.random.seed(seed)
    torch.manual_seed(seed)
    if torch.cuda.is_available():
        torch.cuda.manual_seed_all(seed)


def load_embedding_lookup(path: Path) -> Tuple[Dict[Tuple[str, int], np.ndarray], int]:
    data = load_embedding_archive(path, normalize=True)
    embeddings = data["embeddings"]
    stems = data["stems"]
    stage_indices = data["stage_indices"]
    lookup: Dict[Tuple[str, int], np.ndarray] = {}
    for stem, stage_idx, emb in zip(stems, stage_indices, embeddings):
        lookup[(str(stem), int(stage_idx))] = emb
    return lookup, int(embeddings.shape[1])


def load_combined_embedding_lookup(
    paths: List[Path],
    alignment: str = "intersection",
) -> Tuple[Dict[Tuple[str, int], np.ndarray], int, Dict[str, object]]:
    if not paths:
        raise ValueError("Expected at least one embedding archive path")

    per_path: List[Tuple[Dict[Tuple[str, int], np.ndarray], int]] = [load_embedding_lookup(path) for path in paths]
    base_lookup, base_dim = per_path[0]
    all_key_sets = [set(lookup.keys()) for lookup, _ in per_path]
    if alignment == "strict":
        keys = list(base_lookup.keys())
    else:
        shared_keys = set.intersection(*all_key_sets)
        keys = [key for key in base_lookup.keys() if key in shared_keys]

    dropped_per_archive = []
    for path, (lookup, _), key_set in zip(paths, per_path, all_key_sets):
        dropped = sorted(key_set.difference(keys))
        dropped_per_archive.append(
            {
                "path": str(path),
                "num_keys": int(len(key_set)),
                "num_used_keys": int(len(keys)),
                "num_dropped_keys": int(len(dropped)),
                "sample_dropped_keys": [(str(stem), int(stage_idx)) for stem, stage_idx in dropped[:10]],
            }
        )

    combined_lookup: Dict[Tuple[str, int], np.ndarray] = {}
    total_dim = int(sum(dim for _, dim in per_path))

    for lookup, _ in per_path[1:]:
        missing = [key for key in keys if key not in lookup]
        extra = [key for key in lookup.keys() if key not in base_lookup]
        if alignment == "strict" and (missing or extra):
            raise RuntimeError(
                "Embedding archives do not align on (stem, stage_idx). "
                f"Missing in one archive: {missing[:3]}. Extra in one archive: {extra[:3]}."
            )

    for key in keys:
        parts = [np.asarray(lookup[key], dtype=np.float32) for lookup, _ in per_path]
        combined = np.concatenate(parts, axis=0).astype(np.float32)
        combined /= max(float(np.linalg.norm(combined)), 1e-12)
        combined_lookup[key] = combined

    alignment_info = {
        "mode": alignment,
        "num_shared_keys": int(len(keys)),
        "archives": dropped_per_archive,
    }
    return combined_lookup, total_dim, alignment_info


def load_frame_rows(path: Path, lookup: Dict[Tuple[str, int], np.ndarray]) -> List[Dict[str, object]]:
    rows: List[Dict[str, object]] = []
    for row in read_csv_rows(path, description="Frame manifest"):
        stem = str(row["stem"])
        stage_idx = int(row["stage_idx"])
        key = (stem, stage_idx)
        if key not in lookup:
            raise KeyError(f"Missing embedding lookup for frame {row['frame_key']}")
        rows.append(
            {
                "stem": stem,
                "split": str(row["split"]),
                "stage_idx": stage_idx,
                "frame_key": str(row["frame_key"]),
                "embedding": lookup[key],
            }
        )
    if not rows:
        raise RuntimeError("No frame rows loaded.")
    return rows


def build_prefix_examples(frame_rows: List[Dict[str, object]], context_window: int) -> Tuple[List[Dict[str, object]], int]:
    by_stem: Dict[str, List[Dict[str, object]]] = {}
    for row in frame_rows:
        by_stem.setdefault(str(row["stem"]), []).append(row)

    examples: List[Dict[str, object]] = []
    skipped_noncontiguous = 0
    for stem, stem_rows in by_stem.items():
        stem_rows = sorted(stem_rows, key=lambda row: int(row["stage_idx"]))
        splits = {str(row["split"]) for row in stem_rows}
        if len(splits) != 1:
            raise RuntimeError(f"Expected a single split per stem, got {splits} for stem {stem}")

        for idx in range(len(stem_rows) - 1):
            prefix_rows_full = stem_rows[: idx + 1]
            prefix_stages_full = [int(row["stage_idx"]) for row in prefix_rows_full]
            tgt_row = stem_rows[idx + 1]
            expected_prefix = list(range(prefix_stages_full[0], prefix_stages_full[0] + len(prefix_stages_full)))
            if prefix_stages_full != expected_prefix or int(tgt_row["stage_idx"]) != prefix_stages_full[-1] + 1:
                skipped_noncontiguous += 1
                continue

            prefix_rows = prefix_rows_full[-context_window:] if int(context_window) > 0 else prefix_rows_full
            prefix_stages = [int(row["stage_idx"]) for row in prefix_rows]
            src_stage_idx = prefix_stages[-1]
            tgt_stage_idx = int(tgt_row["stage_idx"])
            examples.append(
                {
                    "stem": stem,
                    "split": str(prefix_rows[0]["split"]),
                    "src_stage_idx": src_stage_idx,
                    "tgt_stage_idx": tgt_stage_idx,
                    "transition_key": f"{stem}_stage{src_stage_idx:02d}_to_stage{tgt_stage_idx:02d}",
                    "src_embeddings": np.stack(
                        [np.asarray(row["embedding"], dtype=np.float32) for row in prefix_rows],
                        axis=0,
                    ),
                    "src_stage_indices": np.asarray(prefix_stages, dtype=np.int64),
                    "tgt_embedding": np.asarray(tgt_row["embedding"], dtype=np.float32),
                }
            )

    if not examples:
        raise RuntimeError("No prefix examples could be built from manifest_frames.csv")
    return examples, skipped_noncontiguous


def split_rows(rows: List[Dict[str, object]]) -> Dict[str, List[Dict[str, object]]]:
    out = {"train": [], "val": [], "test": []}
    for row in rows:
        split = str(row["split"])
        if split in out:
            out[split].append(row)
    for split_name, split_rows in out.items():
        if not split_rows:
            raise RuntimeError(f"No rows found for split: {split_name}")
    return out


