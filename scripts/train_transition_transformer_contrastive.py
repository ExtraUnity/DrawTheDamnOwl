def fit_standardization(rows: List[Dict[str, object]]) -> Tuple[np.ndarray, np.ndarray]:
    vectors: List[np.ndarray] = []
    for row in rows:
        vectors.append(np.asarray(row["src_embeddings"], dtype=np.float32))
        vectors.append(np.asarray(row["tgt_embedding"], dtype=np.float32)[None, :])
    stack = np.concatenate(vectors, axis=0).astype(np.float32)
    mean = stack.mean(axis=0, dtype=np.float32)
    std = stack.std(axis=0, dtype=np.float32)
    std = np.maximum(std, 1e-6).astype(np.float32)
    return mean.astype(np.float32), std


def fit_pca_transform(
    rows: List[Dict[str, object]],
    output_dim: int,
    whiten: bool,
) -> Dict[str, np.ndarray | int | bool]:
    vectors: List[np.ndarray] = []
    for row in rows:
        vectors.append(np.asarray(row["src_embeddings"], dtype=np.float32))
        vectors.append(np.asarray(row["tgt_embedding"], dtype=np.float32)[None, :])
    stack = np.concatenate(vectors, axis=0).astype(np.float32)
    mean = stack.mean(axis=0, dtype=np.float32)
    centered = stack - mean[None, :]

    _, singular_values, vt = np.linalg.svd(centered, full_matrices=False)
    max_dim = int(min(centered.shape[0] - 1, centered.shape[1]))
    if max_dim <= 0:
        raise RuntimeError("Not enough samples to fit PCA transform.")
    proj_dim = int(min(output_dim if output_dim > 0 else centered.shape[1], max_dim))
    components = vt[:proj_dim].T.astype(np.float32)

    denom = max(centered.shape[0] - 1, 1)
    explained_variance = (singular_values[:proj_dim].astype(np.float32) ** 2) / float(denom)
    scales = np.sqrt(np.maximum(explained_variance, 1e-6)).astype(np.float32) if whiten else np.ones((proj_dim,), dtype=np.float32)
    return {
        "mean": mean.astype(np.float32),
        "components": components,
        "scales": scales,
        "output_dim": int(proj_dim),
        "whiten": bool(whiten),
    }


def transform_rows_standardize(rows: List[Dict[str, object]], mean: np.ndarray, std: np.ndarray) -> List[Dict[str, object]]:
    out: List[Dict[str, object]] = []
    for row in rows:
        src_embeddings = np.asarray(row["src_embeddings"], dtype=np.float32)
        tgt_embedding = np.asarray(row["tgt_embedding"], dtype=np.float32)
        src_embeddings = normalize_rows((src_embeddings - mean[None, :]) / std[None, :]).astype(np.float32)
        tgt_embedding = normalize_rows(((tgt_embedding[None, :] - mean[None, :]) / std[None, :]).astype(np.float32))[0]

        out.append(
            {
                **row,
                "src_embeddings": src_embeddings,
                "tgt_embedding": tgt_embedding.astype(np.float32),
            }
        )
    return out


def transform_rows_pca(
    rows: List[Dict[str, object]],
    mean: np.ndarray,
    components: np.ndarray,
    scales: np.ndarray,
) -> List[Dict[str, object]]:
    def project(x: np.ndarray) -> np.ndarray:
        centered = x - mean
        projected = centered @ components
        projected = projected / scales
        return projected.astype(np.float32)

    out: List[Dict[str, object]] = []
    for row in rows:
        src_embeddings = np.asarray(row["src_embeddings"], dtype=np.float32)
        tgt_embedding = np.asarray(row["tgt_embedding"], dtype=np.float32)
        src_projected = np.stack([project(vec) for vec in src_embeddings], axis=0)
        tgt_projected = project(tgt_embedding)
        src_projected = normalize_rows(src_projected).astype(np.float32)
        tgt_projected = normalize_rows(tgt_projected[None, :])[0].astype(np.float32)
        out.append(
            {
                **row,
                "src_embeddings": src_projected,
                "tgt_embedding": tgt_projected,
            }
        )
    return out


class PrefixTransitionDataset(Dataset):
    def __init__(self, rows: List[Dict[str, object]]):
        self.rows = rows

    def __len__(self) -> int:
        return len(self.rows)

    def __getitem__(self, idx: int) -> Dict[str, object]:
        row = self.rows[idx]
        return {
            "src_embeddings": torch.from_numpy(np.asarray(row["src_embeddings"], dtype=np.float32)),
            "src_stage_indices": torch.from_numpy(np.asarray(row["src_stage_indices"], dtype=np.int64)),
            "tgt_embedding": torch.from_numpy(np.asarray(row["tgt_embedding"], dtype=np.float32)),
            "src_stage_idx": torch.tensor(int(row["src_stage_idx"]), dtype=torch.long),
            "tgt_stage_idx": torch.tensor(int(row["tgt_stage_idx"]), dtype=torch.long),
            "transition_key": str(row["transition_key"]),
        }


def collate_prefix_batch(batch: List[Dict[str, object]]) -> Dict[str, object]:
    batch_size = len(batch)
    max_len = max(int(item["src_embeddings"].shape[0]) for item in batch)
    embedding_dim = int(batch[0]["src_embeddings"].shape[1])

    src_embeddings = torch.zeros((batch_size, max_len, embedding_dim), dtype=torch.float32)
    src_stage_indices = torch.zeros((batch_size, max_len), dtype=torch.long)
    src_padding_mask = torch.ones((batch_size, max_len), dtype=torch.bool)
    tgt_embeddings = torch.zeros((batch_size, embedding_dim), dtype=torch.float32)
    src_stage_idx = torch.zeros((batch_size,), dtype=torch.long)
    tgt_stage_idx = torch.zeros((batch_size,), dtype=torch.long)
    transition_keys: List[str] = []

    for row_idx, item in enumerate(batch):
        seq_embeddings = item["src_embeddings"]
        seq_stages = item["src_stage_indices"]
        seq_len = int(seq_embeddings.shape[0])
        src_embeddings[row_idx, :seq_len] = seq_embeddings
        src_stage_indices[row_idx, :seq_len] = seq_stages
        src_padding_mask[row_idx, :seq_len] = False
        tgt_embeddings[row_idx] = item["tgt_embedding"]
        src_stage_idx[row_idx] = item["src_stage_idx"]
        tgt_stage_idx[row_idx] = item["tgt_stage_idx"]
        transition_keys.append(str(item["transition_key"]))

    return {
        "src_embeddings": src_embeddings,
        "src_stage_indices": src_stage_indices,
        "src_padding_mask": src_padding_mask,
        "tgt_embedding": tgt_embeddings,
        "src_stage_idx": src_stage_idx,
        "tgt_stage_idx": tgt_stage_idx,
        "transition_key": transition_keys,
    }


def build_stage_centroids(rows: List[Dict[str, object]]) -> Dict[int, np.ndarray]:
    by_stage: Dict[int, List[np.ndarray]] = {}
    for row in rows:
        stage = int(row["tgt_stage_idx"])
        by_stage.setdefault(stage, []).append(np.asarray(row["tgt_embedding"], dtype=np.float32))

    centroids: Dict[int, np.ndarray] = {}
    for stage, vecs in by_stage.items():
        stack = normalize_rows(np.stack(vecs, axis=0))
        centroid = stack.mean(axis=0, dtype=np.float32)
        centroid /= max(float(np.linalg.norm(centroid)), 1e-12)
        centroids[stage] = centroid.astype(np.float32)
    return centroids


def collect_target_bank(rows: List[Dict[str, object]]) -> Tuple[np.ndarray, List[str]]:
    embeddings = []
    keys = []
    for row in rows:
        embeddings.append(np.asarray(row["tgt_embedding"], dtype=np.float32))
        keys.append(str(row["transition_key"]))
    return normalize_rows(np.stack(embeddings, axis=0)), keys


def build_eval_artifacts(rows: List[Dict[str, object]]) -> Tuple[Dict[int, np.ndarray], np.ndarray, List[str]]:
    return build_stage_centroids(rows), *collect_target_bank(rows)


def retrieval_contrastive_loss(
    pred: torch.Tensor,
    tgt: torch.Tensor,
    temperature: float,
) -> torch.Tensor:
    logits = (pred @ tgt.T) / float(temperature)
    labels = torch.arange(logits.shape[0], device=logits.device)
    return 0.5 * (
        F.cross_entropy(logits, labels)
        + F.cross_entropy(logits.T, labels)
    )


def train_one_epoch(
    model: nn.Module,
    loader: DataLoader,
    optimizer: torch.optim.Optimizer,
    device: torch.device,
    args: argparse.Namespace,
) -> Dict[str, float]:
    model.train()
    losses: List[Dict[str, float]] = []

    for batch in loader:
        src_embeddings = batch["src_embeddings"].to(device)
        src_stage_indices = batch["src_stage_indices"].to(device)
        src_padding_mask = batch["src_padding_mask"].to(device)
        tgt_embedding = batch["tgt_embedding"].to(device)

        valid_mask = (~src_padding_mask).unsqueeze(-1).to(dtype=src_embeddings.dtype)
        if float(args.source_feature_dropout) > 0.0:
            src_embeddings = F.dropout(src_embeddings, p=float(args.source_feature_dropout), training=True)
        if float(args.source_noise_std) > 0.0:
            src_embeddings = src_embeddings + torch.randn_like(src_embeddings) * float(args.source_noise_std) * valid_mask
        src_embeddings = F.normalize(src_embeddings * valid_mask, p=2, dim=-1)

        pred = model(src_embeddings, src_stage_indices, src_padding_mask)
        cosine_loss = 1.0 - torch.sum(pred * tgt_embedding, dim=-1).mean()
        contrastive_loss = retrieval_contrastive_loss(pred, tgt_embedding, args.temperature)
        margin_loss = cosine_loss.new_tensor(0.0)
        loss = (
            float(args.cosine_weight) * cosine_loss
            + float(args.contrastive_weight) * contrastive_loss
            + float(args.margin_loss_weight) * margin_loss
        )

        optimizer.zero_grad(set_to_none=True)
        loss.backward()
        if float(args.grad_clip_norm) > 0.0:
            torch.nn.utils.clip_grad_norm_(model.parameters(), max_norm=float(args.grad_clip_norm))
        optimizer.step()
        losses.append(
            {
                "loss": float(loss.detach().cpu().item()),
                "cosine_loss": float(cosine_loss.detach().cpu().item()),
                "contrastive_loss": float(contrastive_loss.detach().cpu().item()),
                "margin_loss": float(margin_loss.detach().cpu().item()),
            }
        )

    if not losses:
        return {"loss": float("nan"), "cosine_loss": float("nan"), "contrastive_loss": float("nan"), "margin_loss": float("nan")}
    keys = losses[0].keys()
    return {key: float(np.mean([item[key] for item in losses])) for key in keys}


def make_lr_scheduler(optimizer: torch.optim.Optimizer, args: argparse.Namespace):
    warmup_epochs = max(int(args.lr_warmup_epochs), 0)
    total_epochs = max(int(args.epochs), 1)
    min_lr = float(args.min_lr)
    base_lr = float(args.lr)

    def lr_lambda(epoch_idx: int) -> float:
        epoch = epoch_idx + 1
        if warmup_epochs > 0 and epoch <= warmup_epochs:
            return max(epoch / warmup_epochs, min_lr / max(base_lr, 1e-12))

        if total_epochs <= warmup_epochs:
            return min_lr / max(base_lr, 1e-12)

        progress = (epoch - warmup_epochs) / max(total_epochs - warmup_epochs, 1)
        progress = min(max(progress, 0.0), 1.0)
        cosine = 0.5 * (1.0 + np.cos(np.pi * progress))
        return (min_lr + (base_lr - min_lr) * cosine) / max(base_lr, 1e-12)

    return torch.optim.lr_scheduler.LambdaLR(optimizer, lr_lambda=lr_lambda)

def evaluate(
    model: nn.Module,
    loader: DataLoader,
    device: torch.device,
    stage_centroids: Dict[int, np.ndarray],
    target_bank: np.ndarray,
    target_keys: List[str],
) -> Dict[str, float]:
    model.eval()
    cosines: List[float] = []
    centroid_correct = 0
    exact_retrieval_correct = 0
    retrieval_at_5_correct = 0
    total = 0

    stages = sorted(stage_centroids.keys())
    centroid_matrix = np.stack([stage_centroids[s] for s in stages], axis=0)
    stage_to_col = {stage: idx for idx, stage in enumerate(stages)}

    with torch.no_grad():
        for batch in loader:
            src_embeddings = batch["src_embeddings"].to(device)
            src_stage_indices = batch["src_stage_indices"].to(device)
            src_padding_mask = batch["src_padding_mask"].to(device)
            tgt_embedding = batch["tgt_embedding"].to(device)

            pred = model(src_embeddings, src_stage_indices, src_padding_mask)
            batch_cos = torch.sum(pred * tgt_embedding, dim=-1)
            cosines.extend(batch_cos.detach().cpu().tolist())

            pred_np = pred.detach().cpu().numpy().astype(np.float32)
            centroid_scores = pred_np @ centroid_matrix.T
            pred_stage_cols = np.argmax(centroid_scores, axis=1)
            tgt_stages = batch["tgt_stage_idx"].detach().cpu().numpy()
            centroid_correct += int(np.sum(pred_stage_cols == np.array([stage_to_col[s] for s in tgt_stages])))

            retrieval_scores = pred_np @ target_bank.T
            retrieval_idx = np.argmax(retrieval_scores, axis=1)
            topk = min(5, retrieval_scores.shape[1])
            retrieval_topk_idx = np.argpartition(retrieval_scores, -topk, axis=1)[:, -topk:]
            batch_keys = batch["transition_key"]
            exact_retrieval_correct += sum(target_keys[idx] == key for idx, key in zip(retrieval_idx, batch_keys))
            retrieval_at_5_correct += sum(
                key in {target_keys[idx] for idx in row_idx}
                for row_idx, key in zip(retrieval_topk_idx, batch_keys)
            )
            total += pred_np.shape[0]

    return {
        "mean_target_cosine": float(np.mean(cosines)) if cosines else float("nan"),
        "centroid_stage_accuracy": float(centroid_correct / max(total, 1)),
        "exact_target_retrieval_at_1": float(exact_retrieval_correct / max(total, 1)),
        "exact_target_retrieval_at_5": float(retrieval_at_5_correct / max(total, 1)),
        "num_samples": int(total),
    }


def metric_value(metrics: Dict[str, float], args: argparse.Namespace) -> float:
    selection_metric = args.selection_metric
    if selection_metric == "retrieval_at_1":
        return float(metrics["exact_target_retrieval_at_1"])
    if selection_metric == "cosine":
        return float(metrics["mean_target_cosine"])
    if selection_metric == "blended":
        return (
            float(args.blend_retrieval_weight) * float(metrics["exact_target_retrieval_at_1"])
            + float(args.blend_cosine_weight) * float(metrics["mean_target_cosine"])
        )
    raise ValueError(f"Unknown selection metric: {selection_metric}")


def main() -> None:
    args = parse_args()
    set_seed(args.seed)

    embeddings_path = Path(args.embeddings_npz)
    aux_embedding_paths = [Path(path) for path in args.aux_embeddings_npz]
    embedding_paths = [embeddings_path, *aux_embedding_paths]
    output_dir = Path(args.output_dir)
    ensure_dir(output_dir)
    device = torch.device(args.device)

    lookup, embedding_dim, embedding_alignment = load_combined_embedding_lookup(
        embedding_paths,
        alignment=args.embedding_key_alignment,
    )
    frame_rows = load_frame_rows(Path(args.manifest_frames), lookup)
    examples, skipped_noncontiguous = build_prefix_examples(frame_rows, args.context_window)
    splits = split_rows(examples)
    feature_transform = resolve_feature_transform(args.feature_transform, embeddings_path)
    stage_head_mode = resolve_stage_head_mode(args.stage_head_mode, args.disable_stage_specific_output_heads, embeddings_path)

    if feature_transform == "standardize":
        feature_mean, feature_std = fit_standardization(splits["train"])
        splits = {name: transform_rows_standardize(rows, feature_mean, feature_std) for name, rows in splits.items()}
        feature_components = None
        feature_scales = None
        transformed_embedding_dim = embedding_dim
    elif feature_transform in {"pca", "pca_whiten"}:
        pca_transform = fit_pca_transform(
            splits["train"],
            output_dim=args.feature_output_dim,
            whiten=(feature_transform == "pca_whiten"),
        )
        feature_mean = np.asarray(pca_transform["mean"], dtype=np.float32)
        feature_components = np.asarray(pca_transform["components"], dtype=np.float32)
        feature_scales = np.asarray(pca_transform["scales"], dtype=np.float32)
        feature_std = None
        transformed_embedding_dim = int(pca_transform["output_dim"])
        splits = {
            name: transform_rows_pca(rows, feature_mean, feature_components, feature_scales)
            for name, rows in splits.items()
        }
        np.savez_compressed(
            output_dir / "feature_transform.npz",
            mean=feature_mean,
            components=feature_components,
            scales=feature_scales,
            output_dim=np.array([transformed_embedding_dim], dtype=np.int32),
            whiten=np.array([1 if feature_transform == "pca_whiten" else 0], dtype=np.int8),
        )
    else:
        feature_mean = None
        feature_std = None
        feature_components = None
        feature_scales = None
        transformed_embedding_dim = embedding_dim

    max_stage_idx = max(int(row["tgt_stage_idx"]) for row in examples)
    max_seq_len = max(int(np.asarray(row["src_stage_indices"]).shape[0]) for row in examples)

    datasets = {
        "train": PrefixTransitionDataset(splits["train"]),
        "val": PrefixTransitionDataset(splits["val"]),
        "test": PrefixTransitionDataset(splits["test"]),
    }
    pin_memory = device.type == "cuda"
    loaders = {
        "train": DataLoader(
            datasets["train"],
            batch_size=args.batch_size,
            shuffle=True,
            num_workers=args.num_workers,
            pin_memory=pin_memory,
            collate_fn=collate_prefix_batch,
        ),
        "val": DataLoader(
            datasets["val"],
            batch_size=args.batch_size,
            shuffle=False,
            num_workers=args.num_workers,
            pin_memory=pin_memory,
            collate_fn=collate_prefix_batch,
        ),
        "test": DataLoader(
            datasets["test"],
            batch_size=args.batch_size,
            shuffle=False,
            num_workers=args.num_workers,
            pin_memory=pin_memory,
            collate_fn=collate_prefix_batch,
        ),
    }

    model = TransitionSequenceTransformer(
        embedding_dim=transformed_embedding_dim,
        model_dim=args.model_dim,
        num_layers=args.num_layers,
        num_heads=args.num_heads,
        ff_dim=args.ff_dim,
        dropout=args.dropout,
        num_stages=max_stage_idx + 1,
        max_seq_len=max_seq_len,
        stage_embed_dim=args.stage_embed_dim,
        stage_specific_output_heads=(stage_head_mode == "stage-specific"),
    ).to(device)

    optimizer = torch.optim.AdamW(model.parameters(), lr=args.lr, weight_decay=args.weight_decay)
    scheduler = make_lr_scheduler(optimizer, args)
    best_state = None
    best_val_score = -float("inf")
    epochs_without_improvement = 0
    history: List[Dict[str, float]] = []

    val_centroids, val_bank, val_keys = build_eval_artifacts(splits["val"])

    for epoch in range(1, args.epochs + 1):
        train_metrics = train_one_epoch(model, loaders["train"], optimizer, device, args)
        val_metrics = evaluate(model, loaders["val"], device, val_centroids, val_bank, val_keys)
        val_score = metric_value(val_metrics, args)
        epoch_summary = {
            "epoch": float(epoch),
            "train_loss": train_metrics["loss"],
            "train_cosine_loss": train_metrics["cosine_loss"],
            "train_contrastive_loss": train_metrics["contrastive_loss"],
            "train_margin_loss": train_metrics["margin_loss"],
            "val_mean_target_cosine": val_metrics["mean_target_cosine"],
            "val_centroid_stage_accuracy": val_metrics["centroid_stage_accuracy"],
            "val_exact_target_retrieval_at_1": val_metrics["exact_target_retrieval_at_1"],
            "val_exact_target_retrieval_at_5": val_metrics["exact_target_retrieval_at_5"],
            "val_selection_score": val_score,
            "lr": float(optimizer.param_groups[0]["lr"]),
        }
        history.append(epoch_summary)

        if val_score > best_val_score:
            best_val_score = val_score
            best_state = {key: value.detach().cpu().clone() for key, value in model.state_dict().items()}
            epochs_without_improvement = 0
        else:
            epochs_without_improvement += 1

        scheduler.step()

        if epochs_without_improvement >= args.patience:
            break

    if best_state is None:
        raise RuntimeError("Training did not produce a valid checkpoint.")

    model.load_state_dict(best_state)
    torch.save(best_state, output_dir / "best_model.pt")

    train_centroids, train_bank, train_keys = build_eval_artifacts(splits["train"])
    test_centroids, test_bank, test_keys = build_eval_artifacts(splits["test"])
    train_metrics = evaluate(model, loaders["train"], device, train_centroids, train_bank, train_keys)
    val_metrics = evaluate(model, loaders["val"], device, val_centroids, val_bank, val_keys)
    test_metrics = evaluate(model, loaders["test"], device, test_centroids, test_bank, test_keys)

    summary = {
        "embeddings_npz": args.embeddings_npz,
        "aux_embeddings_npz": [str(path) for path in aux_embedding_paths],
        "embedding_sources": [str(path) for path in embedding_paths],
        "embedding_alignment": embedding_alignment,
        "manifest_frames": args.manifest_frames,
        "device": str(device),
        "model_config": {
            "model_dim": args.model_dim,
            "num_layers": args.num_layers,
            "num_heads": args.num_heads,
            "ff_dim": args.ff_dim,
            "stage_embed_dim": args.stage_embed_dim,
            "dropout": args.dropout,
            "context_window": args.context_window,
            "num_stages": max_stage_idx + 1,
            "max_seq_len": max_seq_len,
            "stage_head_mode": stage_head_mode,
            "stage_specific_output_heads": (stage_head_mode == "stage-specific"),
        },
        "training_config": {
            "batch_size": args.batch_size,
            "epochs": args.epochs,
            "lr": args.lr,
            "min_lr": args.min_lr,
            "weight_decay": args.weight_decay,
            "feature_transform": feature_transform,
            "feature_output_dim": args.feature_output_dim,
            "embedding_key_alignment": args.embedding_key_alignment,
            "context_window": args.context_window,
            "grad_clip_norm": args.grad_clip_norm,
            "cosine_weight": args.cosine_weight,
            "contrastive_weight": args.contrastive_weight,
            "margin_loss_weight": args.margin_loss_weight,
            "margin_loss_value": args.margin_loss_value,
            "temperature": args.temperature,
            "source_feature_dropout": args.source_feature_dropout,
            "source_noise_std": args.source_noise_std,
            "stage_head_mode": stage_head_mode,
            "selection_metric": args.selection_metric,
            "blend_retrieval_weight": args.blend_retrieval_weight,
            "blend_cosine_weight": args.blend_cosine_weight,
            "patience": args.patience,
            "lr_warmup_epochs": args.lr_warmup_epochs,
            "seed": args.seed,
        },
        "feature_stats": {
            "mean_norm": float(np.linalg.norm(feature_mean)) if feature_mean is not None else None,
            "std_mean": float(np.mean(feature_std)) if feature_std is not None else None,
            "std_min": float(np.min(feature_std)) if feature_std is not None else None,
            "std_max": float(np.max(feature_std)) if feature_std is not None else None,
            "components_shape": list(feature_components.shape) if feature_components is not None else None,
            "scale_mean": float(np.mean(feature_scales)) if feature_scales is not None else None,
            "scale_min": float(np.min(feature_scales)) if feature_scales is not None else None,
            "scale_max": float(np.max(feature_scales)) if feature_scales is not None else None,
            "transform_path": str(output_dir / "feature_transform.npz") if feature_components is not None else None,
        },
        "num_train": len(splits["train"]),
        "num_val": len(splits["val"]),
        "num_test": len(splits["test"]),
        "embedding_dim": transformed_embedding_dim,
        "raw_embedding_dim": embedding_dim,
        "skipped_noncontiguous_examples": skipped_noncontiguous,
        "best_val_selection_score": best_val_score,
        "train_metrics": train_metrics,
        "val_metrics": val_metrics,
        "test_metrics": test_metrics,
        "history": history,
    }
    write_json(output_dir / "metrics.json", summary)

    print("Transition transformer training complete")
    print(f"Train / Val / Test: {len(splits['train'])} / {len(splits['val'])} / {len(splits['test'])}")
    print(f"Max prefix length:   {max_seq_len}")
    print(f"Best val score:      {best_val_score:.4f} ({args.selection_metric})")
    print(f"Test cosine:         {test_metrics['mean_target_cosine']:.4f}")
    print(f"Test stage acc:      {test_metrics['centroid_stage_accuracy']:.4f}")
    print(f"Test retrieval@1:    {test_metrics['exact_target_retrieval_at_1']:.4f}")
    print(f"Test retrieval@5:    {test_metrics['exact_target_retrieval_at_5']:.4f}")
    print(f"Output dir:          {output_dir}")


if __name__ == "__main__":
    main()
